print("Number of Confirmed Cases:", top_date_count)

# ==========================================
# 15. Top 10 Countries Visualization
# ==========================================

top_10_countries = country_cases.head(10)

plt.figure(figsize=(10, 5))

top_10_countries.plot(kind="bar")

plt.title("Top 10 Countries/Regions by Confirmed COVID-19 Cases")
plt.xlabel("Country / Region")
plt.ylabel("Number of Confirmed Cases")

plt.xticks(rotation=45)

plt.tight_layout()

plt.show()

# ==========================================
# 15(a). Top 10 Countries Heatmap
# ==========================================

top_10_countries = country_cases.head(10)

# Convert data into 2D array
heatmap_data = top_10_countries.values.reshape(-1, 1)

plt.figure(figsize=(8, 6))

plt.imshow(heatmap_data, cmap='YlOrRd', aspect='auto')

plt.colorbar(label="Confirmed COVID-19 Cases")

plt.yticks(
    np.arange(len(top_10_countries)),
    top_10_countries.index
)

plt.xticks([0], ["Confirmed Cases"])

plt.title("Top 10 Countries/Regions by Confirmed COVID-19 Cases")

# Display values inside heatmap
for i in range(len(top_10_countries)):
    plt.text(
        0, i,
        f"{heatmap_data[i, 0]:,.0f}",
        ha="center",
        va="center",
        color="black"
    )

plt.tight_layout()
plt.show()

# ==========================================
# 15(b). Top 10 Countries Line Chart
# ==========================================

top_10_countries = country_cases.head(10)

plt.figure(figsize=(10, 5))

plt.plot(
    top_10_countries.index,
    top_10_countries.values,
    marker='o',
    linestyle='-'
)

plt.title("Top 10 Countries/Regions by Confirmed COVID-19 Cases")
plt.xlabel("Country / Region")
plt.ylabel("Number of Confirmed Cases")

plt.xticks(rotation=45)

plt.grid(True)

plt.tight_layout()

plt.show()

